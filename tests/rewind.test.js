const assert = require('node:assert/strict');
const {analyze} = require('../rewind-data.js');
const data = require('../data/results.json');
const catalog = require('../data/catalog.json');
const scoring = require('../scoring.js');
const all = analyze(data,catalog);
assert.equal(all.count,107);
assert.equal(all.total,213115);
assert.equal(all.standings[0].player.name,'THEJMAXX');
assert.equal(all.best[0].points,3100);
assert.equal(all.best[0].song.title,'Doppelganger');
assert.equal(all.completeJudgments,107);
assert.equal(all.missingScores,1);
assert.equal(all.unknownSongs,3);
assert.equal(all.singles+all.doubles,all.count);
assert.equal(all.grades.reduce((s,g)=>s+g.count,0),all.count);
assert.equal(all.judgmentCount,Object.values(all.judgmentTotals).reduce((a,b)=>a+b));
assert.ok(all.perfectPercent>0&&all.perfectPercent<=100);
for(const row of all.standings){
 const player=analyze(data,catalog,row.player.id);
 assert.equal(player.total,row.total);
 assert.equal(player.count,row.plays.length);
 assert.ok(player.plays.every(p=>p.result.player===row.player.id));
 assert.deepEqual(player,analyze(data,catalog,row.player.id),'regeneration is deterministic');
}
const attempt={id:'a',player:'p',songId:'s',song:'Known song',valid:true,level:10,grade:'AAA',mode:'Single',cut:'Arcade',perfect:90,great:10,good:0,bad:0,miss:0,combo:90,score:900000};
const fixture={event:{minLevel:5,maxLevel:23},players:[{id:'p',name:'P'},{id:'q',name:'Q'}],results:[attempt,{...attempt,id:'retry',grade:'AA'},{...attempt,id:'b',player:'q'},{...attempt,id:'invalid',songId:'x',valid:false}]};
const cat={songs:[{id:'s',title:'Known song'}]};
const tied=analyze(fixture,cat);
assert.equal(tied.count,2,'duplicate and invalid attempts are not counted');
assert.equal(tied.total,2200,'AAA factor is used');
assert.deepEqual(tied.standings.map(s=>s.rank),[1,1]);
assert.equal(tied.best.length,2,'preserve tied highlights');
assert.equal(tied.popular[0].count,2,'popularity counts unique players');
assert.equal(tied.perfectPercent,90);
const missing=analyze({...fixture,results:[{...attempt,perfect:null,score:null,combo:null,songIdentityVerified:false}]},cat);
assert.equal(missing.perfectPercent,null);
assert.equal(missing.completeJudgments,0);
assert.equal(missing.missingScores,1);
assert.equal(missing.maxCombo,null);
assert.equal(missing.popular.length,0);
assert.equal(missing.total,1100,'unreadable machine score does not erase grade points');
const empty=analyze({...fixture,results:[]},cat);
assert.equal(empty.count,0);assert.equal(empty.perfectPercent,null);assert.equal(empty.highLevel,null);assert.deepEqual(empty.best,[]);
assert.throws(()=>analyze(data,catalog,'unknown'),/Unknown player/);
assert.equal(all.total,scoring.counted(data.results,data.event).reduce((s,p)=>s+p.points,0));
console.log('Rewind analytics passed: current data, every player, ties, retries, missing data and empty snapshots.');
